/// The exact `protoc --version` output required by this repository.
pub(crate) const EXPECTED_PROTOC_VERSION: &str = "libprotoc 35.1";

/// Committed `prost` binding regenerated by `build.rs`.
const PROST_GENERATED_BINDING: &str = "proto/perftools.profiles.rs";

/// Parsed arguments for `just x proto`.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum Args {
  /// Install and validate the pinned `protoc` tool.
  Setup,
  /// Force-refresh committed generated protobuf artifacts.
  Update,
  /// Run generation-driving codec checks without forcing a refresh first.
  Gen,
}

/// Validated protobuf toolchain paths.
#[derive(Clone, Debug, Eq, PartialEq)]
pub(crate) struct Toolchain {
  /// Absolute or shim-resolved `protoc` path returned by `proto`.
  protoc: String,
}

impl Toolchain {
  /// Return the validated `protoc` path.
  #[must_use]
  pub(crate) fn protoc(&self) -> &str {
    &self.protoc
  }

  /// Render a short human-facing summary.
  fn summary(&self) -> String {
    format!("{} at {}", EXPECTED_PROTOC_VERSION, self.protoc)
  }
}

/// A generation-driving Cargo step definition.
#[derive(Clone, Debug, Eq, PartialEq)]
struct GenerationStepSpec {
  /// Human-facing step label.
  label:    &'static str,
  /// Codec feature that drives the generation path.
  features: &'static str,
}

/// Cargo checks that drive the committed and `OUT_DIR` protobuf generation paths.
const GENERATION_STEPS: &[GenerationStepSpec] = &[
  GenerationStepSpec {
    label:    "generate prost bindings",
    features: "prost-codec",
  },
  GenerationStepSpec {
    label:    "generate protobuf bindings",
    features: "protobuf-codec",
  },
];

/// One generation-driving Cargo step.
#[derive(Clone, Debug, Eq, PartialEq)]
struct GenerationStep {
  /// Human-facing step label.
  label: &'static str,
  /// Cargo arguments for the step.
  args:  Vec<String>,
}

/// Backup of the committed generated binding before a forced refresh.
#[derive(Clone, Debug, Eq, PartialEq)]
struct GeneratedBindingBackup {
  /// Path that was removed for regeneration.
  path: PathBuf,
  /// Original exact file bytes, if the file existed.
  body: Option<Vec<u8>>,
}

impl GeneratedBindingBackup {
  /// Restore the original file only when regeneration left it absent.
  ///
  /// # Errors
  ///
  /// Returns an I/O error if the path cannot be queried or restored.
  fn restore_if_missing(&self, context: &CommandContext) -> template_core::Result<()> {
    let Some(body) = self.body.as_ref() else {
      return Ok(());
    };
    if context.file_system().path_state(&self.path)? == PathState::Missing {
      context.file_system().write_bytes(&self.path, body)?;
    }
    Ok(())
  }
}

/// Declare the command's `bpaf` options.
#[allow(
  clippy::single_call_fn,
  reason = "a named options() keeps the extension parser beside the proto command it configures"
)]
fn options() -> OptionParser<Args> {
  let setup = pure(Args::Setup)
    .to_options()
    .descr("Install and validate pinned protoc")
    .command("setup");
  let update = pure(Args::Update)
    .to_options()
    .descr("Force-refresh committed protobuf artifacts")
    .command("update");
  let gen_parser = pure(Args::Gen)
    .to_options()
    .descr("Run protobuf generation checks")
    .command("gen");

  construct!([setup, update, gen_parser])
    .to_options()
    .descr("Run pprof protobuf maintenance commands")
}

/// Run the proto extension command.
///
/// # Errors
///
/// Returns a workflow error when the pinned `protoc` version is unavailable or
/// invalid, returns I/O errors while forcing committed binding regeneration,
/// and returns process errors from failed generation steps.
#[allow(
  clippy::single_call_fn,
  reason = "extension dispatch calls the handler once through ProjectCommand::run"
)]
pub(crate) fn execute(context: &CommandContext, args: Args) -> template_core::Result<()> {
  execute_with_root(context, args, &workspace::root()?)
}

/// Registry entry point referenced from `xtask/src/extensions.rs`.
#[must_use]
#[allow(
  clippy::single_call_fn,
  reason = "the command() seam is consumed once by the local extension registry"
)]
pub(crate) fn command() -> template_core::Result<ExtensionCommand<ProjectCommand>> {
  extension_command(
    "proto",
    "Run protobuf setup, update, and generation helpers",
    options(),
    ProjectCommand::Proto,
  )
}

/// Install and validate the pinned `protoc` binary.
///
/// # Errors
///
/// Returns process errors from `proto` or `protoc`, and returns a workflow error
/// if `proto` reports no path or `protoc --version` is not the expected version.
pub(crate) fn setup_toolchain(context: &CommandContext) -> template_core::Result<Toolchain> {
  context.status(StatusKind::Probe, plain("installing pinned protoc"))?;
  let install_arguments = vec!["install".to_owned(), "protoc".to_owned()];
  let install_request = context.process_request(
    "proto",
    &install_arguments,
    ToolColor::EnvOnly,
    OutputPolicy::Inherit,
    OutputPolicy::Inherit,
    &[],
  );
  let install_output = context.execute_process(&install_request)?;
  drop(require_success(&install_request, install_output)?);

  let locate_arguments = vec![
    "--reporter".to_owned(),
    "text".to_owned(),
    "bin".to_owned(),
    "protoc".to_owned(),
  ];
  let locate_request = context.process_request(
    "proto",
    &locate_arguments,
    ToolColor::CapturedPlain,
    OutputPolicy::Capture,
    OutputPolicy::Inherit,
    &[],
  );
  let locate_output = context.execute_process(&locate_request)?;
  let located = require_success(&locate_request, locate_output)?;
  let protoc = String::from_utf8_lossy(&located.stdout).trim().to_owned();
  if protoc.is_empty() {
    return Err(workflow_error("proto returned an empty protoc path"));
  }

  let version_arguments = vec!["--version".to_owned()];
  let version_request = context.process_request(
    &protoc,
    &version_arguments,
    ToolColor::CapturedPlain,
    OutputPolicy::Capture,
    OutputPolicy::Inherit,
    &[],
  );
  let version_output = context.execute_process(&version_request)?;
  let observed_version = require_success(&version_request, version_output)?;
  let version_text = String::from_utf8_lossy(&observed_version.stdout);
  let version = version_text.trim();
  if version != EXPECTED_PROTOC_VERSION {
    return Err(workflow_error(format!(
      "expected `{EXPECTED_PROTOC_VERSION}` from `{protoc} --version`, got `{version}`"
    )));
  }

  Ok(Toolchain {
    protoc,
  })
}

/// Run `just x proto ...` with an explicit workspace root.
///
/// # Errors
///
/// Returns setup, I/O, or generation process errors for the selected command.
#[allow(
  clippy::single_call_fn,
  reason = "explicit-root execution lets update/gen tests exercise file effects without touching the real repository"
)]
pub(crate) fn execute_with_root(context: &CommandContext, args: Args, root: &Path) -> template_core::Result<()> {
  match args {
    Args::Setup => run_setup(context),
    Args::Update => run_update(context, root),
    Args::Gen => run_gen(context, root),
  }
}

/// Run the setup subcommand.
#[allow(
  clippy::single_call_fn,
  reason = "setup has distinct user-facing output after toolchain validation"
)]
fn run_setup(context: &CommandContext) -> template_core::Result<()> {
  let toolchain = setup_toolchain(context)?;
  context.status(StatusKind::Ok, plain(format!("proto: {}", toolchain.summary())))
}

/// Run the update subcommand.
#[allow(
  clippy::single_call_fn,
  reason = "update combines forced artifact refresh with rollback-on-generation-failure semantics"
)]
fn run_update(context: &CommandContext, root: &Path) -> template_core::Result<()> {
  let toolchain = setup_toolchain(context)?;
  let backup = force_refresh_prost_binding(context, root)?;
  match run_generation_checks(context, root, &toolchain) {
    Ok(()) => Ok(()),
    Err(error) => {
      backup.restore_if_missing(context)?;
      Err(error)
    }
  }
}

/// Run the gen subcommand.
#[allow(
  clippy::single_call_fn,
  reason = "gen names the non-mutating generation-driving path separately from forced update"
)]
fn run_gen(context: &CommandContext, root: &Path) -> template_core::Result<()> {
  let toolchain = setup_toolchain(context)?;
  run_generation_checks(context, root, &toolchain)
}

/// Remove the committed `prost` artifact so `build.rs` must regenerate it.
#[allow(
  clippy::single_call_fn,
  reason = "the forced-refresh filesystem operation is isolated so rollback semantics stay visible"
)]
fn force_refresh_prost_binding(context: &CommandContext, root: &Path) -> template_core::Result<GeneratedBindingBackup> {
  let path = root.join(PROST_GENERATED_BINDING);
  context.status(StatusKind::Info, plain(format!("proto: refreshing {PROST_GENERATED_BINDING}")))?;
  let body = if context.file_system().path_state(&path)? == PathState::Missing {
    None
  } else {
    let body = context.file_system().read_bytes(&path)?;
    context.file_system().remove_path(&path)?;
    Some(body)
  };
  Ok(GeneratedBindingBackup {
    path,
    body,
  })
}

/// Run Cargo checks that drive both protobuf generation paths.
fn run_generation_checks(context: &CommandContext, root: &Path, toolchain: &Toolchain) -> template_core::Result<()> {
  for step in generation_steps(root) {
    context.status(StatusKind::Info, plain(format!("proto: {}", step.label)))?;
    let environment = [EnvironmentChange::Set {
      name:  "PROTOC".into(),
      value: toolchain.protoc().into(),
    }];
    let request = context.process_request(
      "cargo",
      &step.args,
      ToolColor::CargoGlobal,
      OutputPolicy::Inherit,
      OutputPolicy::Inherit,
      &environment,
    );
    let output = context.execute_process(&request)?;
    drop(require_success(&request, output)?);
  }
  Ok(())
}

/// Build generation-driving Cargo steps.
#[allow(
  clippy::single_call_fn,
  reason = "generation step construction is test-pinned separately from command execution"
)]
fn generation_steps(root: &Path) -> Vec<GenerationStep> {
  GENERATION_STEPS
    .iter()
    .map(|step| GenerationStep {
      label: step.label,
      args:  cargo_args("check", root, &["--features", step.features, "--locked"]),
    })
    .collect()
}

/// Build Cargo arguments with an absolute manifest path.
#[allow(
  clippy::single_call_fn,
  reason = "proto generation checks share the same manifest anchoring contract"
)]
fn cargo_args(subcommand: &str, root: &Path, args: &[&str]) -> Vec<String> {
  let mut owned = vec![
    subcommand.to_owned(),
    "--manifest-path".to_owned(),
    root.join("Cargo.toml").display().to_string(),
  ];
  owned.extend(args.iter().map(|arg| (*arg).to_owned()));
  owned
}

/// Build a workflow-specific error.
pub(crate) fn workflow_error(message: impl Into<String>) -> template_core::CoreError {
  crate::error::workflow(message)
}


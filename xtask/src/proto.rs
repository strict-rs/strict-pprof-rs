  fn virtual_root() -> PathBuf {
    PathBuf::from("/workspace")
  }

  fn manifest_path(root: &Path) -> String {
    root.join("Cargo.toml").display().to_string()
  }

  fn expected_generation_requests(context: &CommandContext, root: &Path, protoc: &str) -> Vec<ProcessRequest> {
    let manifest = manifest_path(root);
    let environment = protoc_environment(protoc);
    vec![
      extension_request(
        context,
        "cargo",
        &[
          "check",
          "--manifest-path",
          &manifest,
          "--features",
          "prost-codec",
          "--locked",
        ],
        ToolColor::CargoGlobal,
        OutputPolicy::Inherit,
        &environment,
      ),
      extension_request(
        context,
        "cargo",
        &[
          "check",
          "--manifest-path",
          &manifest,
          "--features",
          "protobuf-codec",
          "--locked",
        ],
        ToolColor::CargoGlobal,
        OutputPolicy::Inherit,
        &environment,
      ),
    ]
  }

  fn owned_arguments(arguments: &[&str]) -> Vec<String> {
    arguments.iter().map(|argument| (*argument).to_owned()).collect()
  }
